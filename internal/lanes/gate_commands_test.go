// TestThePolicyAnswersEachCommand holds what a lane that writes and one that only reads are answered, command by command.
func TestThePolicyAnswersEachCommand(t *testing.T) {
	waits := DefaultWaitRules()
	policyOf := func(readOnly bool) DenyPolicy {
		spec := PolicySpec{
			Worktree: "/work/app-lanes/lane-1", Home: "/home/person", DefaultBranches: []string{"main", "master"}, Kept: []string{"feature/kept"},
			Writable: []string{"/run/t/lane-1"}, ReadOnlyRoots: []string{"/work/other"}, ReadOnly: readOnly, Waits: &waits,
		}
		if !readOnly {
			for _, gate := range []string{
				"Bash(git tag *)", "Bash(npm publish:*)", "Bash(gh pr merge *)", "Bash(make deploy *)", "Bash(kubectl delete *)", "Bash(terraform apply *)",
			} {
				spec.Gates = append(spec.Gates, ReadGate(gate))
			}
		}
		return CompilePolicy(spec)
	}
	for _, group := range commandAnswers {
		policy := policyOf(group.readOnly)
		for _, command := range group.commands {
			call, got := shellCall(command), answerPass
			call.Tool = group.tool
			if reason, rule, denied := policy.DecideRule(call); denied {
				got = reason
				if rule != "" {
					got = answerWait
				}
			} else if reason, asks := policy.Asks(call); asks {
				got = reason
			}
			if got != group.answer {
				t.Errorf("%s %q, read-only %v: %q, want %q", group.tool, command, group.readOnly, got, group.answer)
			}
		}
	}
}
