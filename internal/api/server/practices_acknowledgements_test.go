// Withdrawing removes the acknowledgement, so the finding reads as the plain finding it was, and records its event with
// the reason that was withdrawn. One that does not exist is not found.
func TestWithdrawingAnAcknowledgementRestoresThePlainFinding(t *testing.T) {
	d := practicesDaemon(t, nil, "")
	d.HoldClone(t, "repo-a", "widgets")
	keepFindings(t, d)
	made, err := d.Client.AcknowledgePractices(t.Context(), api.PracticesAcknowledge{Repository: "widgets", Finding: secretFinding, Reason: "a fixture"})
	if err != nil {
		t.Fatal(err)
	}
	removed, err := d.Client.WithdrawPractices(t.Context(), api.PracticesWithdraw{Repository: "widgets", Finding: secretFinding})
	if err != nil || removed != made {
		t.Fatalf("withdrawing answered %+v (%v), want the acknowledgement it removed, %+v", removed, err, made)
	}
	list, err := d.Client.Practices(t.Context(), "widgets")
	if err != nil {
		t.Fatal(err)
	}
	view := list.Repositories[0]
	if len(view.Acknowledgement) != 0 || len(view.Result.Findings) != 2 {
		t.Fatalf("the read holds %+v, want both findings and no acknowledgement", view)
	}
	for _, finding := range view.Result.Findings {
		if finding.Acknowledged || finding.Acknowledgement != nil {
			t.Errorf("the finding %s reads acknowledged after the withdrawal", finding.ID)
		}
	}
	events := eventsOf(t, d, ledger.EventPracticesWithdrawn)
	if len(events) != 1 || events[0].Subject != ledger.PracticesFindingSubject("repo-a", secretFinding) {
		t.Fatalf("the events read %+v", events)
	}
	var data map[string]any
	if err := json.Unmarshal(events[0].Data, &data); err != nil || data["finding"] != secretFinding || data["repository"] != "repo-a" || data["reason"] != "a fixture" || data["member"] != "member-1" {
		t.Errorf("the event holds %v (%v)", data, err)
	}
	_, err = d.Client.WithdrawPractices(t.Context(), api.PracticesWithdraw{Repository: "widgets", Finding: secretFinding})
	refusedWith(t, err, http.StatusNotFound, api.CodeNotFound)
	_, err = d.Client.WithdrawPractices(t.Context(), api.PracticesWithdraw{Repository: "widgets", Finding: "no-such-practice"})
	refusedWith(t, err, http.StatusBadRequest, api.CodeInvalid)
	_, err = d.Client.WithdrawPractices(t.Context(), api.PracticesWithdraw{Repository: "nothing", Finding: "codeowners"})
	refusedWith(t, err, http.StatusNotFound, api.CodeNotFound)
	if _, err := d.Client.AcknowledgePractices(t.Context(), api.PracticesAcknowledge{Repository: "widgets", Finding: secretFinding, Reason: "acknowledged again"}); err != nil {
		t.Errorf("acknowledging a withdrawn finding again: %v", err)
	}
}

// A delegate's call to acknowledge is a card, whatever its policy exempts, which names the finding, why it matters,
// and the reason; it records nothing until a member confirms it, and then the acknowledgement is the confirming
// member's.
func TestADelegatesAcknowledgementIsACardAMemberConfirms(t *testing.T) {
	d := practicesDaemon(t, nil, "")
	d.HoldClone(t, "repo-a", "widgets")
	keepFindings(t, d)
	created := aDelegate(t, d.Client.Client, apitest.ProjectName)
	delegate := asDelegate(t, d.Socket, created.Token, apitest.ProjectName)
	_, err := delegate.AcknowledgePractices(t.Context(), api.PracticesAcknowledge{Repository: "widgets", Finding: secretFinding, Reason: "a fixture the parser tests read"})
	card := preparedCard(t, err)
	detail := cardDetail(t, card)
	if detail.Operation != authority.OpPracticesAcknowledge || detail.Label != "Acknowledge a practices finding" {
		t.Errorf("the card is of %s, %q", detail.Operation, detail.Label)
	}
	var shown []authority.FieldChange
	if err := json.Unmarshal(detail.Changes, &shown); err != nil || len(shown) != 3 {
		t.Fatalf("the card shows %s (%v)", detail.Changes, err)
	}
	secrets, _ := practices.Lookup(practices.Secrets)
	if shown[0].Field != "finding" || shown[0].To != secretFinding || shown[1].Field != "why" || shown[1].To != secrets.Why || shown[2].Field != "reason" || shown[2].To != "a fixture the parser tests read" {
		t.Errorf("the card shows %+v, want the finding, why it matters, and the reason", shown)
	}
	if !strings.Contains(card.Summary, "widgets") {
		t.Errorf("the card is titled %q, want the repository's name", card.Summary)
	}
	if events := eventsOf(t, d, ledger.EventPracticesAcknowledged); len(events) != 0 {
		t.Fatalf("the card recorded %d acknowledgements before a member confirmed it", len(events))
	}
	confirmCard(t, d, err)
	list, err := d.Client.Practices(t.Context(), "widgets")
	if err != nil || len(list.Repositories[0].Acknowledgement) != 1 || list.Repositories[0].Acknowledgement[0].Member != "member-1" {
		t.Errorf("the read holds %+v (%v), want the acknowledgement made by the confirming member", list.Repositories[0].Acknowledgement, err)
	}
	events := eventsOf(t, d, ledger.EventPracticesAcknowledged)
	if len(events) != 1 || events[0].Actor.Kind != ledger.ActorMember {
		t.Errorf("the events read %+v, want one by the member", events)
	}
}

