func TestAcknowledgingRefusesWhatCannotBeAcknowledged(t *testing.T) {
	d := practicesDaemon(t, nil, "")
	d.HoldClone(t, "repo-a", "widgets")
	if _, err := d.Client.AcknowledgePractices(t.Context(), api.PracticesAcknowledge{Repository: "widgets", Finding: "codeowners", Reason: "the team owns it"}); err != nil {
		t.Fatal(err)
	}
	for name, tc := range map[string]struct {
		in     api.PracticesAcknowledge
		status int
		code   string
	}{
		"an empty reason":                {api.PracticesAcknowledge{Repository: "widgets", Finding: "security-policy"}, http.StatusBadRequest, api.CodeInvalid},
		"a reason of spaces":             {api.PracticesAcknowledge{Repository: "widgets", Finding: "security-policy", Reason: " \n "}, http.StatusBadRequest, api.CodeInvalid},
		"a reason over 2 KiB":            {api.PracticesAcknowledge{Repository: "widgets", Finding: "security-policy", Reason: strings.Repeat("x", ledger.MaxPracticesReason+1)}, http.StatusBadRequest, api.CodeInvalid},
		"a finding no practice names":    {api.PracticesAcknowledge{Repository: "widgets", Finding: "no-such-practice", Reason: "x"}, http.StatusBadRequest, api.CodeInvalid},
		"a malformed finding":            {api.PracticesAcknowledge{Repository: "widgets", Finding: "secrets:github_token", Reason: "x"}, http.StatusBadRequest, api.CodeInvalid},
		"an acknowledgement that exists": {api.PracticesAcknowledge{Repository: "widgets", Finding: "codeowners", Reason: "again"}, http.StatusConflict, api.CodeAcknowledged},
		"a repository the project lacks": {api.PracticesAcknowledge{Repository: "nothing", Finding: "codeowners", Reason: "x"}, http.StatusNotFound, api.CodeNotFound},
	} {
		_, err := d.Client.AcknowledgePractices(t.Context(), tc.in)
		t.Run(name, func(t *testing.T) { refusedWith(t, err, tc.status, tc.code) })
	}
	if events := eventsOf(t, d, ledger.EventPracticesAcknowledged); len(events) != 1 {
		t.Errorf("%d acknowledgement events, want the first one's only: a refusal records nothing", len(events))
	}
	exactly := strings.Repeat("x", ledger.MaxPracticesReason)
	if _, err := d.Client.AcknowledgePractices(t.Context(), api.PracticesAcknowledge{Repository: "widgets", Finding: "security-policy", Reason: exactly}); err != nil {
		t.Errorf("a reason of exactly 2 KiB is refused: %v", err)
	}
}

